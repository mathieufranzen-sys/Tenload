-- ════════════════════════════════════════════════════════════════════════════
--  Tendo — schéma Supabase
--
--  À exécuter une fois, en entier, dans l'éditeur SQL de Supabase.
--  Tableau de bord > SQL Editor > New query > coller > Run.
--
--  Principe de sécurité : chaque table active Row Level Security et chaque
--  politique filtre sur auth.uid(). Un utilisateur ne peut voir et écrire que
--  ses propres lignes, même si la clé publique de l'app fuite — elle est faite
--  pour être publique. La seule exception est strava_tokens, qui n'a AUCUNE
--  politique : la table est donc totalement inaccessible depuis le navigateur.
--  Seules les fonctions Netlify, qui utilisent la clé de service, y touchent.
-- ════════════════════════════════════════════════════════════════════════════

-- ─── Profil ─────────────────────────────────────────────────────────────────
create table if not exists public.profiles (
  id                  uuid primary key references auth.users on delete cascade,
  display_name        text,
  -- Allure marathon OBJECTIF en secondes par kilomètre. Ancre les six zones.
  -- 277 = 4:37/km = 3 h 15.
  marathon_pace_s     integer not null default 277,
  -- Allure marathon projetée par le dernier test. 289 = 4:49/km = 3 h 23.
  fitness_pace_s      integer not null default 289,
  -- Dernier test de 3 km, en secondes. 722 = 12:02.
  test_3k_s           integer,
  test_3k_date        date,
  -- Fréquence cardiaque maximale mesurée. 181 pour Mathieu, et non les 193
  -- que Strava suppose : voir la section « Zones cardiaques » du CLAUDE.md.
  hr_max              integer not null default 181,
  goal_label          text not null default '3 h 15',
  race_date           date not null default '2027-04-11',
  plan_start          date not null default '2026-08-10',
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);

-- ─── Journal quotidien (le carnet de suivi tendon) ──────────────────────────
create table if not exists public.daily_logs (
  user_id       uuid not null references auth.users on delete cascade,
  day           date not null,
  -- Les trois mesures de douleur, 0 à 10. La raideur au réveil est le marqueur
  -- de référence, la douleur du soir est celle qui parle le plus chez Mathieu.
  pain_wake     numeric(3,1) check (pain_wake between 0 and 10),
  pain_effort   numeric(3,1) check (pain_effort between 0 and 10),
  pain_evening  numeric(3,1) check (pain_evening between 0 and 10),
  -- Gestes protecteurs : ils font BAISSER l'indice de charge du tendon.
  eccentric     boolean not null default false,
  icing         boolean not null default false,
  jumps         boolean not null default false,
  stretching    boolean not null default false,
  hydration_l   numeric(3,1),
  mood          text,
  note          text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  primary key (user_id, day)
);
create index if not exists daily_logs_user_day_idx on public.daily_logs (user_id, day desc);

-- ─── Ressenti après chaque séance ───────────────────────────────────────────
create table if not exists public.session_feedback (
  user_id       uuid not null references auth.users on delete cascade,
  -- Repère de la séance dans le plan : semaine 1-35, jour 0-6, index dans la journée.
  week          smallint not null check (week between 1 and 60),
  day_index     smallint not null check (day_index between 0 and 6),
  slot          smallint not null default 0,
  day           date not null,
  session_type  text not null,
  -- Douleur au tendon pendant et juste après la séance, 0 à 10.
  pain          numeric(3,1) not null check (pain between 0 and 10),
  -- Effort perçu, échelle RPE 0 à 10.
  rpe           smallint not null check (rpe between 0 and 10),
  distance_km   numeric(5,2),
  note          text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  primary key (user_id, week, day_index, slot)
);
create index if not exists session_feedback_user_day_idx
  on public.session_feedback (user_id, day desc);

-- ─── Activités importées (Strava, ou saisie manuelle) ───────────────────────
create table if not exists public.activities (
  id               bigint generated by default as identity primary key,
  user_id          uuid not null references auth.users on delete cascade,
  source           text not null default 'strava',
  external_id      text,
  day              date not null,
  started_at       timestamptz,
  sport            text not null,
  name             text,
  distance_m       numeric(10,1) not null default 0,
  moving_s         integer not null default 0,
  elapsed_s        integer,
  elevation_m      numeric(7,1),
  avg_hr           numeric(5,1),
  max_hr           numeric(5,1),
  avg_watts        numeric(6,1),
  relative_effort  integer,
  created_at       timestamptz not null default now(),
  unique (user_id, source, external_id)
);
create index if not exists activities_user_day_idx on public.activities (user_id, day desc);

-- ─── Modifications manuelles du plan ────────────────────────────────────────
-- Le plan des 35 semaines vit dans le code (src/data/plan.json) : c'est une
-- donnée de référence, pas une donnée utilisateur. Cette table ne stocke que
-- les écarts volontaires, pour ne pas dupliquer 315 séances par utilisateur.
create table if not exists public.plan_overrides (
  user_id     uuid not null references auth.users on delete cascade,
  week        smallint not null,
  day_index   smallint not null,
  slot        smallint not null default 0,
  patch       jsonb not null,
  reason      text,
  created_at  timestamptz not null default now(),
  primary key (user_id, week, day_index, slot)
);

-- ─── Jetons Strava — jamais accessibles depuis le navigateur ────────────────
create table if not exists public.strava_tokens (
  user_id       uuid primary key references auth.users on delete cascade,
  athlete_id    bigint,
  access_token  text not null,
  refresh_token text not null,
  expires_at    timestamptz not null,
  scope         text,
  last_sync_at  timestamptz,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

