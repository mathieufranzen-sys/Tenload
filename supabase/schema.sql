-- Un profil est créé automatiquement à la première connexion.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, coalesce(new.raw_user_meta_data->>'name', split_part(new.email, '@', 1)))
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- updated_at tenu à jour tout seul.
create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end $$;

drop trigger if exists touch_profiles on public.profiles;
create trigger touch_profiles before update on public.profiles
  for each row execute function public.touch_updated_at();

drop trigger if exists touch_daily_logs on public.daily_logs;
create trigger touch_daily_logs before update on public.daily_logs
  for each row execute function public.touch_updated_at();

drop trigger if exists touch_session_feedback on public.session_feedback;
create trigger touch_session_feedback before update on public.session_feedback
  for each row execute function public.touch_updated_at();

drop trigger if exists touch_strava_tokens on public.strava_tokens;
create trigger touch_strava_tokens before update on public.strava_tokens
  for each row execute function public.touch_updated_at();

-- ════════════════════════════════════════════════════════════════════════════
--  Vue de commodité : la charge tendineuse par jour, calculée côté base.
--
--  L'app calcule déjà l'indice en TypeScript (src/lib/tendonIndex.ts), ce qui
--  lui permet de fonctionner hors ligne. Cette vue sert aux vérifications et à
--  d'éventuelles tâches planifiées côté serveur — les deux calculs doivent
--  donner le même résultat, les coûts sont ceux de KM_COST et MIN_COST.
-- ════════════════════════════════════════════════════════════════════════════
create or replace view public.daily_tendon_load as
select
  user_id,
  day,
  round(sum(
    case
      when sport = 'Run' then
        (distance_m / 1000.0) * case
          when name ~* 'fractionn|x800|x400|x200|test' then 0.45 * 2.1 + 0.55 * 1.0
          when name ~* 'seuil|tempo'                   then 0.45 * 1.6 + 0.55 * 1.0
          when distance_m >= 18000                     then 1.15
          else 1.0
        end
      when sport = 'Ride'   then (moving_s / 60.0) * 0.10
      when sport = 'Weight' then (moving_s / 60.0)
                                 * case when name ~* 'jambe|bas|bulgare|trx' then 0.25 else 0.0 end
      when sport = 'Hike'   then (moving_s / 60.0) * 0.05
      else 0
    end
  )::numeric, 2) as load_km_eq
from public.activities
group by user_id, day;

comment on view public.daily_tendon_load is
  'Charge tendineuse quotidienne en kilomètres-équivalents. Doit rester alignée sur KM_COST et MIN_COST dans src/lib/tendonIndex.ts.';
